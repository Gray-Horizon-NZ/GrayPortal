"use client";
import { useEffect, useState, type FormEvent } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { Loader2 } from "lucide-react";
import {
  verifyPasswordResetCode,
  confirmPasswordReset,
  signInWithEmailAndPassword,
  getMultiFactorResolver,
  type MultiFactorResolver,
  type MultiFactorError,
} from "firebase/auth";
import { firebaseAuth } from "@/lib/firebase/client";
import WizardShell from "@/components/onboardingWizard/WizardShell";
import { completeSignIn } from "../login/completeSignIn";
import MfaChallenge from "../login/MfaChallenge";

const MIN_LENGTH = 8;
const FORM_ID = "reset-password-form";

// Lands here from either the emailed link generated by
// generatePasswordResetLink (src/lib/dal/passwordAuth.ts) — a first
// password or a genuine forgot-password reset, Firebase doesn't distinguish
// the two — or from the portal-setup invite's first step (`invite` set).
// The invite flow does NOT sign in afterwards: it hands straight back to
// /onboard/[token] for the wizard, and the client's first real sign-in
// happens from the wizard's "Enter Client Portal" (where MFA enrolment and
// the onboarding-completion email belong).
export default function ResetPasswordForm({
  oobCode,
  invite,
  clientName,
}: {
  oobCode: string | null;
  invite: string | null;
  clientName: string | null;
}) {
  const router = useRouter();

  const [status, setStatus] = useState<"checking" | "ready" | "invalid">(() => (oobCode ? "checking" : "invalid"));
  const [email, setEmail] = useState<string | null>(null);
  const [password, setPassword] = useState("");
  const [confirm, setConfirm] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [mfaResolver, setMfaResolver] = useState<MultiFactorResolver | null>(null);

  useEffect(() => {
    if (!oobCode) return;
    verifyPasswordResetCode(firebaseAuth, oobCode)
      .then((resolvedEmail) => {
        setEmail(resolvedEmail);
        setStatus("ready");
      })
      .catch(() => setStatus("invalid"));
  }, [oobCode]);

  function finish() {
    router.push("/");
    router.refresh();
  }

  async function handleSubmit(e: FormEvent) {
    e.preventDefault();
    setError(null);
    if (password.length < MIN_LENGTH) {
      setError(`Password must be at least ${MIN_LENGTH} characters.`);
      return;
    }
    if (password !== confirm) {
      setError("Passwords don't match.");
      return;
    }
    if (!oobCode || !email) return;

    setBusy(true);
    try {
      await confirmPasswordReset(firebaseAuth, oobCode, password);
      if (invite) {
        router.push(`/onboard/${invite}`);
        return;
      }
      // Signs them straight in rather than bouncing back to a separate
      // login step — a freshly-set password is exactly what they'd type
      // there anyway.
      const result = await signInWithEmailAndPassword(firebaseAuth, email, password);
      const outcome = await completeSignIn(result.user);
      if (!outcome.ok) {
        setError(outcome.error);
        setBusy(false);
        return;
      }
      finish();
    } catch (err) {
      if (err && typeof err === "object" && "code" in err && err.code === "auth/multi-factor-auth-required") {
        setMfaResolver(getMultiFactorResolver(firebaseAuth, err as MultiFactorError));
        setBusy(false);
        return;
      }
      setError(
        invite
          ? "Couldn't set your password. The link may have expired — open the button in your invite email again."
          : "Couldn't set your password. The link may have expired — request a new one from the login page."
      );
      setBusy(false);
    }
  }

  const action =
    status === "ready" && !mfaResolver ? (
      <button className="gh-btn-primary" type="submit" form={FORM_ID} disabled={busy}>
        {busy ? (
          <span style={{ display: "inline-flex", alignItems: "center", gap: "var(--gh-space-2)" }}>
            <Loader2 className="gh-spin" size={14} strokeWidth={2} />
            Setting password…
          </span>
        ) : invite ? (
          "Set password & continue"
        ) : (
          "Set password"
        )}
      </button>
    ) : undefined;

  return (
    <WizardShell
      clientName={clientName ?? ""}
      stepIndex={0}
      stepCount={0}
      heading={
        clientName ? undefined : (
          <>
            Gray <em>Portal</em>
          </>
        )
      }
      stepLabel={invite ? "Before we begin" : "Account"}
      action={action}
    >
      {mfaResolver ? (
        <MfaChallenge resolver={mfaResolver} onSuccess={finish} onError={setError} />
      ) : status === "checking" ? (
        <p style={{ color: "var(--gh-text-muted)", fontSize: "var(--gh-text-sm)", display: "inline-flex", alignItems: "center", gap: "var(--gh-space-2)" }}>
          <Loader2 className="gh-spin" size={14} strokeWidth={2} />
          Checking your link…
        </p>
      ) : status === "invalid" ? (
        <div style={{ display: "flex", flexDirection: "column", gap: "var(--gh-space-4)" }}>
          <h1 className="gh-title" style={{ fontSize: "var(--gh-text-2xl)" }}>
            This link has <em>expired</em>
          </h1>
          {invite ? (
            <p style={{ color: "var(--gh-text-muted)" }}>
              Password links only last an hour.{" "}
              <Link href={`/onboard/${invite}`} style={{ color: "var(--gh-accent)" }}>
                Get a fresh one
              </Link>{" "}
              — or press the button in your invite email again.
            </p>
          ) : (
            <p style={{ color: "var(--gh-text-muted)" }}>
              Request a new one from the{" "}
              <Link href="/login" style={{ color: "var(--gh-accent)" }}>
                login page
              </Link>
              .
            </p>
          )}
        </div>
      ) : (
        <form id={FORM_ID} onSubmit={handleSubmit} style={{ display: "flex", flexDirection: "column", gap: "var(--gh-space-6)" }}>
          <div style={{ display: "flex", flexDirection: "column", gap: "var(--gh-space-3)" }}>
            <h1 className="gh-title" style={{ fontSize: "var(--gh-text-2xl)" }}>
              {invite ? (
                <>
                  First, set your <em>password</em>.
                </>
              ) : (
                <>
                  Set a new <em>password</em>.
                </>
              )}
            </h1>
            <p style={{ color: "var(--gh-text-muted)" }}>
              {invite
                ? "You'll use this to sign in to your portal. Then we'll walk you through a few quick steps."
                : "Choose a new password for your Gray Portal account."}
            </p>
          </div>

          <div style={{ display: "flex", flexDirection: "column", gap: "var(--gh-space-3)" }}>
            <label style={{ display: "flex", flexDirection: "column", gap: "var(--gh-space-1)" }}>
              <span style={{ fontSize: "var(--gh-text-xs)", color: "var(--gh-text-muted)" }}>Email</span>
              <input className="gh-input" type="email" value={email ?? ""} readOnly autoComplete="username" style={{ color: "var(--gh-text-muted)" }} />
            </label>
            <label style={{ display: "flex", flexDirection: "column", gap: "var(--gh-space-1)" }}>
              <span style={{ fontSize: "var(--gh-text-xs)", color: "var(--gh-text-muted)" }}>Password</span>
              <input
                className="gh-input"
                type="password"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
                autoComplete="new-password"
                required
                minLength={MIN_LENGTH}
                autoFocus
              />
            </label>
            <label style={{ display: "flex", flexDirection: "column", gap: "var(--gh-space-1)" }}>
              <span style={{ fontSize: "var(--gh-text-xs)", color: "var(--gh-text-muted)" }}>Confirm password</span>
              <input
                className="gh-input"
                type="password"
                value={confirm}
                onChange={(e) => setConfirm(e.target.value)}
                autoComplete="new-password"
                required
                minLength={MIN_LENGTH}
              />
            </label>
            <p style={{ fontSize: "var(--gh-text-xs)", color: "var(--gh-text-muted)" }}>At least {MIN_LENGTH} characters.</p>
          </div>

          {error && <p style={{ color: "var(--gh-danger)", fontSize: "var(--gh-text-sm)" }}>{error}</p>}

          {!invite && (
            <Link href="/login" style={{ fontSize: "var(--gh-text-xs)", color: "var(--gh-text-muted)" }}>
              ← Back to sign in
            </Link>
          )}
        </form>
      )}
    </WizardShell>
  );
}
